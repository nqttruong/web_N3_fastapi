"""OCR engines. Default: local Tesseract (``jpn`` traineddata) called as a subprocess.

No shell is used, the image path is generated by the server, and a timeout bounds runtime.
OCR output is always treated as uncertain: every question parsed from it is flagged for
review and no answer read by OCR is ever confirmed automatically.
"""

import functools
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

from app.core.config import Settings
from app.imports.textutil import collapse_ocr_spacing


class OcrError(Exception):
    pass


@dataclass(frozen=True)
class OcrAvailability:
    available: bool
    engine: str | None
    languages: list[str]
    reason: str | None


class OcrEngine(Protocol):
    name: str

    def availability(self) -> OcrAvailability: ...

    def recognise(self, image_path: Path) -> str: ...


class NoOcrEngine:
    name = "none"

    def availability(self) -> OcrAvailability:
        return OcrAvailability(False, None, [], "OCR đã bị tắt (OCR_ENGINE=none).")

    def recognise(self, image_path: Path) -> str:
        raise OcrError("OCR is disabled")


class TesseractEngine:
    def __init__(self, cmd: str, languages: str, psm: int, timeout: int) -> None:
        self.cmd = cmd
        self.languages = languages
        self.psm = psm
        self.timeout = timeout
        self.name = f"tesseract:{languages}"

    @functools.cache  # noqa: B019 — engine instances are long-lived singletons
    def availability(self) -> OcrAvailability:
        binary = shutil.which(self.cmd)
        if binary is None:
            return OcrAvailability(
                False,
                "tesseract",
                [],
                f"Không tìm thấy Tesseract ('{self.cmd}'). Cài tesseract + gói ngôn ngữ jpn, "
                "hoặc dùng “Dán văn bản”.",
            )
        try:
            proc = subprocess.run(
                [binary, "--list-langs"], capture_output=True, text=True, timeout=15, check=False
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            return OcrAvailability(False, "tesseract", [], f"Không chạy được Tesseract: {exc}")
        installed = {
            line.strip() for line in (proc.stdout + proc.stderr).splitlines()[1:] if line.strip()
        }
        wanted = [lang for lang in self.languages.split("+") if lang]
        missing = [lang for lang in wanted if lang not in installed]
        if missing:
            return OcrAvailability(
                False,
                "tesseract",
                sorted(installed),
                f"Tesseract thiếu dữ liệu ngôn ngữ: {', '.join(missing)}.",
            )
        return OcrAvailability(True, "tesseract", wanted, None)

    def recognise(self, image_path: Path) -> str:
        binary = shutil.which(self.cmd)
        if binary is None:
            raise OcrError("tesseract not found")
        argv = [binary, str(image_path), "stdout", "-l", self.languages, "--psm", str(self.psm)]
        try:
            proc = subprocess.run(argv, capture_output=True, timeout=self.timeout, check=False)
        except subprocess.TimeoutExpired as exc:
            raise OcrError(f"OCR quá thời gian ({self.timeout}s)") from exc
        except OSError as exc:
            raise OcrError(str(exc)) from exc
        if proc.returncode != 0:
            raise OcrError(proc.stderr.decode("utf-8", "replace")[-500:] or "tesseract failed")
        return collapse_ocr_spacing(proc.stdout.decode("utf-8", "replace"))


_engine_override: OcrEngine | None = None


def set_engine_for_tests(engine: OcrEngine | None) -> None:
    global _engine_override
    _engine_override = engine


@functools.cache
def _engine_from(cmd: str, languages: str, psm: int, timeout: int, kind: str) -> OcrEngine:
    if kind == "none":
        return NoOcrEngine()
    return TesseractEngine(cmd, languages, psm, timeout)


def get_engine(settings: Settings) -> OcrEngine:
    if _engine_override is not None:
        return _engine_override
    return _engine_from(
        settings.ocr_tesseract_cmd,
        settings.ocr_languages,
        settings.ocr_psm,
        settings.ocr_timeout_seconds,
        settings.ocr_engine,
    )
