"""Import drafts: user-supplied text/HTML/screenshots, parsed into an editable preview.

Nothing in a draft touches ``exams``/``questions`` until the user commits it.
"""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    SmallInteger,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.base import Base, CreatedAtMixin, TimestampMixin, UUIDPrimaryKeyMixin
from app.database.enums import ImportMethod, ImportStatus, OcrStatus, check_in

IMAGE_MIME_TYPES = ("image/png", "image/jpeg", "image/webp")


class ImportDraft(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    __tablename__ = "import_drafts"

    status: Mapped[str] = mapped_column(Text, nullable=False)
    method: Mapped[str] = mapped_column(Text, nullable=False)
    # Adapter that produced `content` (e.g. "dethitiengnhat_html", "generic_text").
    adapter: Mapped[str | None] = mapped_column(Text, nullable=True)
    source_url: Mapped[str | None] = mapped_column(Text, nullable=True)
    # Original text/HTML exactly as pasted (never rendered as HTML). NULL for image imports.
    raw_input: Mapped[str | None] = mapped_column(Text, nullable=True)
    # sha256 of the raw input (or of the ordered image hashes): detects re-importing it.
    raw_sha256: Mapped[str] = mapped_column(Text, nullable=False)
    # Editable preview: exam meta, passages, questions, attempt info (see imports/schemas.py).
    content: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    # Last validation result: list of issues.
    issues: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, nullable=False)
    error_code: Mapped[str | None] = mapped_column(Text, nullable=True)
    error_message: Mapped[str | None] = mapped_column(Text, nullable=True)
    # Optimistic concurrency for PATCH.
    version: Mapped[int] = mapped_column(Integer, nullable=False, default=1, server_default="1")
    exam_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("exams.id", ondelete="SET NULL"), nullable=True
    )
    committed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    assets: Mapped[list["ImportAsset"]] = relationship(
        back_populates="draft",
        cascade="all, delete-orphan",
        order_by="ImportAsset.position",
        lazy="selectin",
    )

    __table_args__ = (
        CheckConstraint(check_in("status", ImportStatus), name="status_valid"),
        CheckConstraint(check_in("method", ImportMethod), name="method_valid"),
        CheckConstraint("source_url IS NULL OR source_url ~* '^https?://'", name="source_url_http"),
        CheckConstraint("jsonb_typeof(content) = 'object'", name="content_is_object"),
        CheckConstraint("jsonb_typeof(issues) = 'array'", name="issues_is_array"),
        CheckConstraint(
            "status <> 'committed' OR committed_at IS NOT NULL", name="committed_has_timestamp"
        ),
        CheckConstraint(
            "(method = 'images') = (raw_input IS NULL)", name="raw_input_matches_method"
        ),
        Index("ix_import_drafts_status", "status"),
        Index("ix_import_drafts_created_at", "created_at"),
        Index("ix_import_drafts_raw_sha256", "raw_sha256"),
        Index("ix_import_drafts_source_url", "source_url"),
        Index("ix_import_drafts_exam_id", "exam_id"),
        Index(
            "uq_import_drafts_browser_capture_retry",
            "raw_sha256",
            unique=True,
            postgresql_where=text("method = 'browser_capture'"),
        ),
    )


class ImportAsset(UUIDPrimaryKeyMixin, CreatedAtMixin, Base):
    __tablename__ = "import_assets"

    draft_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("import_drafts.id", ondelete="CASCADE"), nullable=False
    )
    position: Mapped[int] = mapped_column(SmallInteger, nullable=False)
    # Relative to IMPORT_STORAGE_DIR; generated by the server, never from the client filename.
    storage_path: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    original_filename: Mapped[str | None] = mapped_column(Text, nullable=True)
    detected_type: Mapped[str] = mapped_column(Text, nullable=False)  # from file content
    stored_type: Mapped[str] = mapped_column(Text, nullable=False)  # always image/png
    byte_size: Mapped[int] = mapped_column(BigInteger, nullable=False)
    width: Mapped[int] = mapped_column(Integer, nullable=False)
    height: Mapped[int] = mapped_column(Integer, nullable=False)
    sha256: Mapped[str] = mapped_column(Text, nullable=False)
    ocr_status: Mapped[str] = mapped_column(Text, nullable=False)
    ocr_engine: Mapped[str | None] = mapped_column(Text, nullable=True)
    ocr_text: Mapped[str | None] = mapped_column(Text, nullable=True)

    draft: Mapped[ImportDraft] = relationship(back_populates="assets")

    __table_args__ = (
        UniqueConstraint(
            "draft_id",
            "position",
            name="uq_import_assets_draft_position",
            deferrable=True,
            initially="DEFERRED",
        ),
        CheckConstraint("position >= 0", name="position_non_negative"),
        CheckConstraint(
            "detected_type IN (" + ", ".join(f"'{t}'" for t in IMAGE_MIME_TYPES) + ")",
            name="detected_type_valid",
        ),
        CheckConstraint("stored_type = 'image/png'", name="stored_type_png"),
        CheckConstraint("byte_size > 0 AND width > 0 AND height > 0", name="dimensions_positive"),
        CheckConstraint(check_in("ocr_status", OcrStatus), name="ocr_status_valid"),
        CheckConstraint("storage_path !~ '(^/|\\.\\.)'", name="storage_path_relative"),
    )
