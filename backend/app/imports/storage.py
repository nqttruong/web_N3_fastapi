"""Local file storage for uploaded screenshots.

Paths stored in the database are relative (``<draft_id>/<asset_id>.png``) and generated by
the server. ``resolve`` rejects anything that would escape the storage root.
"""

import shutil
import uuid
from pathlib import Path

from app.core.config import Settings
from app.core.errors import AppError


class StorageError(AppError):
    code = "storage_error"


def root(settings: Settings) -> Path:
    base = Path(settings.import_storage_dir).resolve()
    base.mkdir(parents=True, exist_ok=True)
    return base


def relative_path(draft_id: uuid.UUID, asset_id: uuid.UUID) -> str:
    return f"{draft_id}/{asset_id}.png"


def resolve(settings: Settings, relative: str) -> Path:
    base = root(settings)
    candidate = (base / relative).resolve()
    if relative.startswith(("/", "\\")) or ".." in Path(relative).parts:
        raise StorageError("Đường dẫn tệp không hợp lệ.")
    if not candidate.is_relative_to(base):
        raise StorageError("Đường dẫn tệp không hợp lệ.")
    return candidate


def write_bytes(settings: Settings, relative: str, data: bytes) -> Path:
    path = resolve(settings, relative)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_bytes(data)
    tmp.replace(path)
    return path


def delete_draft_dir(settings: Settings, draft_id: uuid.UUID) -> None:
    path = resolve(settings, str(draft_id))
    if path.is_dir():
        shutil.rmtree(path, ignore_errors=True)
